import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const url = process.env.DSH_VERIFY_URL
assert(url && new URL(url).port === '3186', 'Explicit private 3186 URL required')
const output = new URL('../../.work/dsh-home/evidence/', import.meta.url)
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const checks = []
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addLocatorHandler(page.getByRole('button', { name: 'Continue', exact: true }), async () => page.getByRole('button', { name: 'Continue', exact: true }).click())
  await page.addLocatorHandler(page.getByRole('heading', { name: /^(Get started|开始使用)$/ }), async () => page.getByRole('button', { name: /^(Close|关闭)$/ }).last().click())
  await page.goto(url)
  const open = async () => {
    await page.getByRole('button', { name: /^(Home|首页)$/ }).first().click()
    await page.locator('.dsh-home').waitFor()
  }
  const order = () => page.locator('[data-layout-surface=unified] > [data-widget-id]').evaluateAll(els => els.map(el => el.dataset.widgetId))
  const api = (op) => page.evaluate(async op => {
    const r = await fetch('/plugins/dsh-home/api', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ op }) })
    const body = await r.json(); if (!body.ok) throw new Error('API failed'); return body.value
  }, op)
  await open()
  assert.equal(await page.locator('.dsh-drag').count(), 0)
  assert.equal(await page.locator('.dsh-home[data-editing=false]').count(), 1)
  const edit = () => page.getByRole('button', { name: /^(Edit layout|编辑布局)$/, exact: true }).click()
  const done = () => page.getByRole('button', { name: /^(Done|完成)$/, exact: true }).click()
  await edit()
  await page.locator('.dsh-home[data-editing=true]').waitFor()
  assert((await page.locator('.dsh-drag').count()) >= 9)
  assert.equal(await page.locator('[data-widget-id=resume] .dsh-drag').count(), 1)
  assert.equal(await page.locator('[data-widget-id=queue] .dsh-drag').count(), 1)
  checks.push('header edit mode reveals all widget handles in one grid')
  const before = await order()
  if (before.indexOf('resume') < before.indexOf('recent')) {
    // Make repeated runs exercise an actual cross-region move rather than a no-op.
    const h = page.locator('[data-widget-id=resume] .dsh-drag')
    await h.focus()
    while ((await order()).indexOf('resume') < (await order()).indexOf('recent')) await h.press('ArrowRight')
  }
  const dragBefore = await order()
  const source = page.locator('[data-widget-id=resume] .dsh-drag')
  const target = page.locator('[data-widget-id=recent]')
  await source.scrollIntoViewIfNeeded()
  const from = await source.boundingBox()
  const to = await target.boundingBox()
  assert(from && to)
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
  await page.mouse.down()
  await page.mouse.move(to.x + 20, Math.max(90, to.y + 8), { steps: 20 })
  await page.mouse.up()
  const after = await order()
  assert.notDeepEqual(after, dragBefore, 'Pointer drag must change real DOM order')
  assert(after.indexOf('resume') < after.indexOf('recent'), 'Focus card crosses old region boundary')
  checks.push('real pointer drag reorders focus and recent cards across old regions')
  await done()
  await page.locator('.dsh-home[data-editing=false]').waitFor()
  assert.equal(await page.locator('.dsh-drag').count(), 0)
  const saved = (await api('layout.get')).layout
  assert(saved.order.indexOf('resume') < saved.order.indexOf('recent'))
  await page.reload(); await open()
  assert.deepEqual(await order(), after)
  checks.push('Done persists unified layout; reload preserves order and reading mode')
  await edit()
  await page.locator('[data-widget-id=queue]').getByRole('button', { name: /^(Hide this card|隐藏这张卡)$/ }).click()
  assert.equal(await page.locator('[data-widget-id=queue]').count(), 0)
  await page.getByRole('button', { name: /^(Widgets|小组件)$/, exact: true }).click()
  await page.locator('.dsh-tray-item').filter({ hasText: /^(Waiting on you|在等我)/ }).click()
  await page.locator('[data-widget-id=queue]').waitFor()
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await page.locator('.dsh-home[data-editing=false]').waitFor()
  checks.push('focus widgets removable/restorable; Esc closes tray then saves editor')
  await edit()
  const handle = page.locator('[data-widget-id=tasks] .dsh-drag')
  await handle.focus(); await handle.press('ArrowLeft')
  await done()
  await page.locator('.dsh-home[data-editing=false]').waitFor()
  checks.push('keyboard reorder works in editing mode')
  await edit()
  const rejectSave = async route => {
    if (route.request().postDataJSON()?.op === 'layout.set') await route.fulfill({ status: 500, json: { ok: false, error: { message: 'editor save negative control' } } })
    else await route.continue()
  }
  await page.route('**/plugins/dsh-home/api', rejectSave)
  await done()
  await page.locator('.dsh-error').filter({ hasText: /Could not save|布局未能保存/ }).waitFor()
  assert.equal(await page.locator('.dsh-home[data-editing=true]').count(), 1)
  await page.unroute('**/plugins/dsh-home/api', rejectSave)
  await done()
  await page.locator('.dsh-home[data-editing=false]').waitFor()
  checks.push('save failure remains editable; explicit Done retry succeeds')
  await page.screenshot({ path: new URL('editor-reading.png', output).pathname, fullPage: true })
  await edit()
  await page.locator('.dsh-home').evaluate(el => { el.scrollTop = 0 })
  await page.screenshot({ path: new URL('editor-active.png', output).pathname, fullPage: true })
  await page.keyboard.press('Escape')
  await page.locator('.dsh-home[data-editing=false]').waitFor()
  assert.equal(await page.evaluate(() => document.body.classList.contains('dsh-home-dragging')), false)
  assert.deepEqual(errors, [])
  await writeFile(new URL('editor-report.json', output), JSON.stringify({ checks, errors }, null, 2))
  console.log(checks.map(s => 'PASS ' + s).join('\n'))
} catch (error) {
  console.error(error)
  process.exitCode = 1
} finally { await browser.close() }
