#!/usr/bin/env node
/**
 * Compile `src/client/theme.css` to a TS module exporting the CSS as a string.
 *
 * The client half injects one stylesheet into `<head>` (see `styles.ts`), so the
 * Tailwind output has to become a JS string rather than an asset file. Keeping
 * it in TS also means the plugin tarball stays a single `lib/client.js`.
 *
 *   pnpm run build:css          # compile
 *   pnpm run build:css --check  # fail when the committed output is stale
 */
import { execFileSync } from 'node:child_process'
import { mkdtemp, readFile, writeFile, mkdir, rm } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { createHash } from 'node:crypto'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const INPUT = path.join(ROOT, 'src/client/theme.css')
const OUTPUT = path.join(ROOT, 'src/client/ui/generated/theme-css.ts')
const BIN = path.join(ROOT, 'node_modules/.bin/tailwindcss')

if (!existsSync(BIN)) {
  console.error('tailwindcss CLI missing — run `pnpm install` first')
  process.exit(1)
}

const tmp = await mkdtemp(path.join(os.tmpdir(), 'dsh-home-css-'))
const raw = path.join(tmp, 'theme.css')
try {
  execFileSync(BIN, ['-i', INPUT, '-o', raw, '--minify'], { cwd: ROOT, stdio: 'pipe' })
} catch (error) {
  console.error(error.stdout?.toString() ?? '')
  console.error(error.stderr?.toString() ?? error.message)
  process.exit(1)
}

const css = await readFile(raw, 'utf8')
await rm(tmp, { recursive: true, force: true })

const digest = createHash('sha256').update(css).digest('hex').slice(0, 16)
const module = `/**
 * GENERATED by scripts/build-css.mjs — do not edit.
 * Source: src/client/theme.css · bytes: ${Buffer.byteLength(css)} · sha256: ${digest}
 */
export const themeCss = ${JSON.stringify(css)}
`

const check = process.argv.includes('--check')
const current = existsSync(OUTPUT) ? await readFile(OUTPUT, 'utf8') : null
if (check) {
  if (current !== module) {
    console.error('compiled theme is stale — run `pnpm run build:css`')
    process.exit(1)
  }
  console.log(`compiled theme is current (${Buffer.byteLength(css)} bytes, ${digest})`)
  process.exit(0)
}

await mkdir(path.dirname(OUTPUT), { recursive: true })
await writeFile(OUTPUT, module)
console.log(`wrote ${path.relative(ROOT, OUTPUT)} (${Buffer.byteLength(css)} bytes, sha256 ${digest})`)
